function [Tall,TallHistory]=parseModelUpdatingFolder(folderPath,filePattern)
%BUILDMODELUPDATINGSUMMARYTABLE Build summary table from report files
%
% Tall = buildModelUpdatingSummaryTable(folderPath)
% Tall = buildModelUpdatingSummaryTable(folderPath, filePattern)
%
% Example:
%   Tall = buildModelUpdatingSummaryTable(pwd, 'ModelUpdating*.txt');

    if nargin < 1 || isempty(folderPath)
        folderPath = pwd;
    end

    if nargin < 2 || isempty(filePattern)
        filePattern = 'ModelUpdatingLMBeam*.txt';
    end

    filePatterParts = regexp(filePattern, '\*', 'split');

    prefixPattern = filePatterParts{1};        % 'ModelUpdatingLMBeam'
    typePattern   = filePatterParts{2};        % '.txt'

    files = dir(fullfile(folderPath, filePattern));

    if isempty(files)
        error('Nessun file trovato con pattern: %s', fullfile(folderPath, filePattern));
    end

    rows = cell(numel(files), 1);
    historyRows = cell(numel(files),1);

    for k = 1:numel(files)
        fullName = fullfile(files(k).folder, files(k).name);

        % Parse del file
        S = parseModelUpdatingReport(fullName);



        % Estrazione info dal nome file
        F = parseReportFileName(files(k).name,prefixPattern);

        % Label automatiche
        formulationLabel = string(F.formulation);
        meshLabel = string(F.meshLabel);
        shortLabel = string(F.shortLabel);

        % Fallback se qualcosa manca nel nome file
        if strlength(formulationLabel) == 0 || formulationLabel == "unknown"
            formulationLabel = string(S.formulation);
        end
        if strlength(meshLabel) == 0 || meshLabel == "unknown"
            meshLabel = sprintf('%dx%dx%d', S.mesh.nx, S.mesh.ny, S.mesh.nz);
            meshLabel = string(meshLabel);
        end
        if strlength(shortLabel) == 0 || shortLabel == "unknown_unknown"
            shortLabel = formulationLabel + "-" + meshLabel;
        end
        shortLabel = formulationLabel + "-" + meshLabel;

        H = S.history;

        H.file = repmat(string(files(k).name), height(H), 1);
        H.formulation = repmat(formulationLabel, height(H), 1);
        H.meshLabel = repmat(meshLabel, height(H), 1);
        H.seriesLabel = repmat(shortLabel, height(H), 1);
        H.DOFs_free = repmat(S.dofs.free, height(H), 1);
        H.DOFs_total = repmat(S.dofs.total, height(H), 1);

        historyRows{k} = H;

        % Riga tabella
        rows{k} = table( ...
            string(files(k).name), ...
            formulationLabel, ...
            meshLabel, ...
            shortLabel, ...
            S.mesh.nx, ...
            S.mesh.ny, ...
            S.mesh.nz, ...
            S.dofs.free, ...
            S.dofs.fixed, ...
            S.dofs.total, ...
            S.summary.initialErrPI(1), ...
            S.summary.initialErrPI(2), ...
            S.summary.initialErrPI(3), ...
            S.summary.initialErrPI(4), ...
            S.summary.initialResNorm, ...
            S.summary.initialRMS, ...
            S.summary.optimalErrPI(1), ...
            S.summary.optimalErrPI(2), ...
            S.summary.optimalErrPI(3), ...
            S.summary.optimalErrPI(4), ...
            S.summary.optimalResNorm, ...
            S.summary.optimalRMS, ...
            S.optimized.density, ...
            S.optimized.young_kPa, ...
            S.optimized.poisson, ...
            S.optimized.thickness_mm, ...
            S.optimized.width_mm, ...
            S.optimized.length_mm, ...
            S.elapsedTime.total, ...
            'VariableNames', { ...
            'file', ...
            'formulation', ...
            'meshLabel', ...
            'seriesLabel', ...
            'nx', ...
            'ny', ...
            'nz', ...
            'DOFs_free', ...
            'DOFs_fixed', ...
            'DOFs_total', ...
            'Err1_init', ...
            'Err2_init', ...
            'Err3_init', ...
            'Err4_init', ...
            'ResNorm_init', ...
            'RMS_init', ...
            'Err1_opt', ...
            'Err2_opt', ...
            'Err3_opt', ...
            'Err4_opt', ...
            'ResNorm_opt', ...
            'RMS_opt', ...
            'rho_opt', ...
            'Y_opt', ...
            'nu_opt', ...
            't_opt', ...
            'b_opt', ...
            'L_opt', ...
            'time_s' ...
            } ...
        );
    end

    Tall = vertcat(rows{:});

    TallHistory = vertcat(historyRows{:});

    % Ordinamento utile per DOFs
    Tall = sortrows(Tall, {'formulation','DOFs_free'});

    % Label breve automatica per legenda o asse
    Tall.legendLabel = Tall.formulation + " (" + Tall.meshLabel + ")";
end

function F = parseReportFileName(fileName,prefixPattern)
% Estrae info dal nome file, ad es.:
% ModelUpdatingLMBeamHexa27-Int27_13x117x1.txt

    F = struct();
    F.formulation = "unknown";
    F.meshLabel = "unknown";
    F.shortLabel = "unknown_unknown";

    [~, baseName, ~] = fileparts(fileName);

    %% --- RIMOZIONE PREFIX ROBUSTA ---
    if strlength(prefixPattern) > 0
        % Rimuove solo se è all'inizio + eventuali _ o -
        baseName = regexprep(baseName, ...
            ['^' regexptranslate('escape', char(prefixPattern)) '[_\-]*'], ...
            '');
    end


   %% --- PARSE PRINCIPALE ---
    tok = regexp(baseName, ...
        '^([A-Za-z0-9\-]+)_([0-9]+x[0-9]+x[0-9]+)$', ...
        'tokens', 'once');

    if ~isempty(tok)
        F.formulation = string(tok{1});
        F.meshLabel = string(tok{2});
        F.shortLabel = F.formulation + "_" + F.meshLabel;
        return;
    end

    %% --- FALLBACK: mesh ---
    tokMesh = regexp(baseName, '([0-9]+x[0-9]+x[0-9]+)', 'tokens', 'once');
    if ~isempty(tokMesh)
        F.meshLabel = string(tokMesh{1});
    end

    %% --- FALLBACK: formulation ---
    tokForm = regexp(baseName, '(Hexa[0-9]+-Int[0-9]+)', 'tokens', 'once');
    if ~isempty(tokForm)
        F.formulation = string(tokForm{1});
    else
        % fallback generico: tutto prima del mesh
        tokForm2 = regexp(baseName, '^([A-Za-z0-9\-]+)', 'tokens', 'once');
        if ~isempty(tokForm2)
            F.formulation = string(tokForm2{1});
        end
    end

    %% --- COSTRUZIONE SHORT LABEL ---
    if F.formulation == "unknown" && F.meshLabel == "unknown"
        F.shortLabel = "unknown_unknown";
    elseif F.meshLabel == "unknown"
        F.shortLabel = F.formulation;
    elseif F.formulation == "unknown"
        F.shortLabel = F.meshLabel;
    else
        F.shortLabel = F.formulation + "-" + F.meshLabel;
    end
end

